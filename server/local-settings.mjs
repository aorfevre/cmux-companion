function invalid(message) { throw new TypeError(message); }
function keys(value, allowed, label) {
  if (!value || typeof value !== 'object' || Array.isArray(value) || Object.keys(value).some(key => !allowed.includes(key))) invalid(`Invalid ${label} fields`);
}
function string(value, label, max = 4096) {
  if (typeof value !== 'string' || !value.trim() || value.length > max || [...value].some(char => char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127)) invalid(`Invalid ${label}`);
  return value;
}
function integer(value, label, max = 2147483647) {
  if (!Number.isSafeInteger(value) || value < 1 || value > max) invalid(`Invalid ${label}`);
}
export function validateExecutable(value) {
  string(value, 'executable');
  if ((!isAbsolute(value) && !/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(value)) || /[;$`|&<>]/.test(value)) invalid('Use an executable name or absolute path, without shell syntax');
  return value;
}
export function providerCommand(value, provider) {
  keys(value, ['executable', 'args', 'model'], `${provider} provider`);
  validateExecutable(value.executable);
  if (!Array.isArray(value.args) || value.args.some(arg => typeof arg !== 'string')) invalid('Provider arguments must be a list');
  const name = basename(value.executable);
  // Provider flags are generated by the adapters, never accepted as a route to
  // override permissions, hooks, MCP or credential handling.
  if (!(name === 'ccs' && value.args.length === 1 && /^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$/.test(value.args[0]))
      && !(name === provider && value.args.length === 0)
      && !(provider === 'codex' && name === 'ccsxp' && value.args.length === 0)
      && !(!isAbsolute(value.executable) && value.args.length === 0)) invalid(`Use a terminal command name, ccs with one profile, or ${provider}; provider flags are managed by Companion`);
  normalizeModelId(value.model);
  return structuredClone(value);
}
function validateSettings(value) {
  keys(value, ['devRepos', 'projects', 'providers', 'provider', 'tools', 'execution', 'previews', 'onboarding', 'launchProfiles', 'teamDefaults'], 'settings');
  keys(value.providers, ['claude', 'codex'], 'providers');
  for (const provider of ['claude', 'codex']) providerCommand(value.providers[provider], provider);
  if (!['claude', 'codex'].includes(value.provider)) invalid('Choose Claude or Codex');
  teamDefaults(value, launchProfiles(value));
  keys(value.tools, ['cmux', 'tailscale', 'chrome'], 'tools');
  for (const name of ['cmux', 'tailscale', 'chrome']) validateExecutable(value.tools[name]);
  keys(value.execution, Object.keys(defaultSettings().execution), 'execution');
  for (const name of Object.keys(defaultSettings().execution)) integer(value.execution[name], name);
  if (value.execution.maxOutputBytes > 2097152 || value.execution.killGraceMs > 30000) invalid('Native output or termination limit is too large');
  keys(value.previews, ['portStart', 'portEnd'], 'preview');
  for (const name of ['portStart', 'portEnd']) integer(value.previews[name], name, 65535);
  if (value.previews.portStart < 1024 || value.previews.portEnd < value.previews.portStart) invalid('Choose an ordered preview port range above 1023');
  keys(value.onboarding, ['completed'], 'onboarding');
  if (typeof value.onboarding.completed !== 'boolean') invalid('Invalid onboarding progress');
  if (!Array.isArray(value.projects) || value.projects.length > 500) invalid('Invalid projects');
  if (!Array.isArray(value.devRepos) || value.devRepos.length > 500) invalid('Invalid Dev repos');
  const rootIds = new Set(), rootNames = new Set(), rootPaths = [];
  for (const root of value.devRepos) {
    keys(root, ['id', 'name', 'path'], 'Dev repo');
    if (typeof root.id !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,79}$/.test(root.id) || rootIds.has(root.id)) invalid('Dev repo IDs must be unique');
    string(root.name, 'Dev repo name', 160); string(root.path, 'Dev repo path');
    if (root.name !== root.name.trim() || rootNames.has(root.name.toLowerCase())) invalid('Dev repo names must be trimmed and unique');
    if (!isAbsolute(root.path) || rootPaths.some(path => contains(path, root.path) || contains(root.path, path))) invalid('Dev repo directories must be distinct and must not overlap');
    rootIds.add(root.id); rootNames.add(root.name.toLowerCase()); rootPaths.push(root.path);
  }
  const ids = new Set(), paths = new Set();
  for (const project of value.projects) {
    keys(project, ['id', 'name', 'path', 'enabled', 'github', 'remote', 'checks', 'devRepoId'], 'project');
    if (typeof project.id !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,79}$/.test(project.id) || ids.has(project.id)) invalid('Project IDs must be unique letters, numbers, underscores or hyphens');
    if (project.devRepoId != null && !rootIds.has(project.devRepoId)) invalid('Unknown Dev repo');
    ids.add(project.id); string(project.name, 'project name', 160); string(project.path, 'project path');
    if (!isAbsolute(project.path) || paths.has(project.path)) invalid('Project paths must be unique absolute paths');
    paths.add(project.path);
    if (typeof project.enabled !== 'boolean') invalid('Invalid project enabled status');
    if (project.github !== null && !/^[A-Za-z0-9_-]+\/[A-Za-z0-9_.-]+$/.test(project.github)) invalid('Use owner/repository for the GitHub destination');
    if (project.remote !== null) {
      string(project.remote, 'remote');
      if (!/^(git@[a-zA-Z0-9.-]+:[^\s]+|ssh:\/\/git@[a-zA-Z0-9.-]+\/[^\s]+|https:\/\/[a-zA-Z0-9.-]+\/[^\s?#]+)$/.test(project.remote)) invalid('Use an SSH or HTTPS remote without embedded credentials');
    }
    if (!Array.isArray(project.checks) || project.checks.length > 50) invalid('Invalid project checks');
    const checks = new Set();
    for (const check of project.checks) {
      keys(check, ['id', 'executable', 'args'], 'check');
      if (typeof check.id !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,79}$/.test(check.id) || checks.has(check.id)) invalid('Check IDs must be unique');
      checks.add(check.id); validateExecutable(check.executable);
      if (['sh', 'bash', 'zsh', 'fish', 'csh', 'dash', 'env'].includes(basename(check.executable))) invalid('Configure the verification executable directly');
      if (!Array.isArray(check.args) || check.args.length > 100) invalid('Invalid check arguments');
      for (const arg of check.args) string(arg, 'check argument');
    }
  }
  return value;
}

export function resolveExecutable(command, searchPath = process.env.PATH || '') {
  validateExecutable(command);
  const candidates = isAbsolute(command) ? [command] : searchPath.split(':').filter(path => isAbsolute(path)).map(path => join(path, command));
  for (const path of candidates) {
    try { accessSync(path, constants.X_OK); const resolved = realpathSync(path); if (lstatSync(resolved).isFile()) return resolved; } catch { /* Try the next PATH entry. */ }
  }
  return null;
}

export async function inspectProject(path, run = execute, { timeout = 5000 } = {}) {
  path = macPath(path);
  string(path, 'project path');
  if (!isAbsolute(path)) invalid('Enter an absolute project directory on this Mac');
  const deadline = Date.now() + timeout;
  const options = () => ({ timeout: Math.max(1, deadline - Date.now()), maxBuffer: 32768 });
  let canonical;
  try {
    canonical = realpathSync(path);
    const result = await run('git', ['-C', canonical, 'rev-parse', '--show-toplevel'], options());
    if (realpathSync(result.stdout.trim()) !== canonical) invalid('Select the root directory of the Git repository');
  } catch { invalid('Project must be an accessible Git repository root on this Mac'); }
  let remote = null;
  try { remote = (await run('git', ['-C', canonical, 'remote', 'get-url', 'origin'], options())).stdout.trim(); } catch { /* Local-only repositories are valid. */ }
  // A repository's config is untrusted and may embed a token. Return only a
  // recognized credential-free GitHub destination as a suggestion.
  const match = remote?.match(/^(?:git@github\.com:|ssh:\/\/git@github\.com\/|https:\/\/github\.com\/)([\w-]+\/[\w.-]+?)(?:\.git)?$/);
  return { path: canonical, name: basename(canonical), github: match?.[1] ?? null, remote: match ? remote : null, suggestedChecks: await suggestedChecks(canonical) };
}

export class LocalSettings {
  constructor({ path = ':memory:' } = {}) {
    this.path = path;
    if (path !== ':memory:') {
      mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
      try { if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink()) invalid('Settings database must be a regular file'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
    this.db = new DatabaseSync(path);
    try {
      const tables = this.db.prepare("SELECT name FROM sqlite_schema WHERE type='table' AND name NOT LIKE 'sqlite_%'").all();
      if (tables.length && !tables.some(table => table.name === 'local_settings')) invalid('Choose a separate settings database; this file belongs to another application or workflow');
      if (path !== ':memory:') chmodSync(path, 0o600);
      this.db.exec('PRAGMA busy_timeout=5000; PRAGMA synchronous=FULL;');
      const version = Number(this.db.prepare('PRAGMA user_version').get().user_version);
      if (version > 2) invalid('Settings database is newer than this version of Companion');
      this.db.exec(`BEGIN IMMEDIATE;
        CREATE TABLE IF NOT EXISTS local_settings (id INTEGER PRIMARY KEY CHECK(id=1), revision INTEGER NOT NULL, value TEXT NOT NULL, imported INTEGER NOT NULL DEFAULT 0);
        CREATE TABLE IF NOT EXISTS project_favorites (project_id TEXT PRIMARY KEY, favorite INTEGER NOT NULL CHECK(favorite IN (0,1)));
        CREATE TABLE IF NOT EXISTS goal_configuration (goal_id TEXT PRIMARY KEY, revision INTEGER NOT NULL, value TEXT NOT NULL);
        COMMIT;`);
      this.db.prepare('INSERT OR IGNORE INTO local_settings(id,revision,value) VALUES(1,0,?)').run(JSON.stringify(defaultSettings()));
      if (version < 2) {
        this.db.exec('BEGIN IMMEDIATE');
        try {
          const current = this.read().settings;
          current.devRepos ??= [];
          validateSettings(current);
          this.db.prepare('UPDATE local_settings SET value=? WHERE id=1').run(JSON.stringify(current));
          this.db.exec('PRAGMA user_version=2; COMMIT;');
        } catch (error) { this.db.exec('ROLLBACK'); throw error; }
      }
      validateSettings(this.read().settings);
    } catch (error) { this.db.close(); throw error; }
  }
  read() {
    const row = this.db.prepare('SELECT revision,value,imported FROM local_settings WHERE id=1').get();
    return { revision: Number(row.revision), settings: JSON.parse(String(row.value)), imported: Boolean(row.imported) };
  }
  async update(expectedRevision, settings, { inspect = inspectProject } = {}) {
    settings = structuredClone(settings);
    if (Array.isArray(settings.devRepos) && Array.isArray(settings.projects)) {
      const saved = this.read().settings;
      for (const project of settings.projects) if (project.devRepoId && !settings.devRepos.some(root => root.id === project.devRepoId) && saved.devRepos.some(root => root.id === project.devRepoId)) delete project.devRepoId;
    }
    validateSettings(settings);
    const before = this.read();
    this.assertRevision(expectedRevision, before.revision);
    const next = structuredClone(settings);
    for (const root of next.devRepos) {
      const existing = before.settings.devRepos.find(entry => entry.id === root.id);
      if (existing && existing.path !== root.path) invalid('Dev repo paths cannot be changed; add another Dev repo');
      if (!existing) root.path = (await inspectDevRepo(root.path)).path;
    }
    for (const project of next.projects) {
      const existing = before.settings.projects.find(entry => entry.id === project.id);
      if (existing && existing.path !== project.path) invalid('Project paths cannot be changed; add another project');
      if (!existing || !existing.enabled && project.enabled) project.path = (await inspect(project.path)).path;
    }
    for (const project of next.projects) {
      const existing = before.settings.projects.find(entry => entry.id === project.id);
      const root = next.devRepos.find(entry => dirname(project.path) === entry.path);
      const priorRoot = before.settings.devRepos.find(entry => entry.id === existing?.devRepoId);
      if (project.devRepoId && !next.devRepos.some(entry => entry.id === project.devRepoId)) delete project.devRepoId;
      if (root && (!existing || !existing.devRepoId || project.devRepoId !== root.id || !existing.enabled && project.enabled)) {
        await assertDevChild(root.path, project.path); project.devRepoId = root.id;
      } else if (project.devRepoId && (!priorRoot || priorRoot.id !== project.devRepoId)) invalid('Repository must belong to its containing Dev repo');
      if (project.devRepoId && next.devRepos.find(entry => entry.id === project.devRepoId)?.path !== dirname(project.path)) invalid('Repository is outside its Dev repo');
    }
    validateSettings(next);
    // Disabling preserves the identity used by historical and running goals.
    if (before.settings.projects.some(project => !next.projects.some(entry => entry.id === project.id))) invalid('Disable projects instead of deleting their history');
    return this.write(expectedRevision, next);
  }
  assertRevision(expected, actual) {
    if (!Number.isSafeInteger(expected) || expected < 0) invalid('Expected settings revision is required');
    if (expected !== actual) { const error = new Error('Settings changed on another device. Reload before saving.'); error.statusCode = 409; throw error; }
  }
  write(expected, settings, imported = false) {
    this.db.exec('BEGIN IMMEDIATE');
    try {
      this.assertRevision(expected, this.read().revision);
      this.db.prepare('UPDATE local_settings SET revision=revision+1,value=?,imported=MAX(imported,?) WHERE id=1').run(JSON.stringify(settings), Number(imported));
      this.db.exec('COMMIT');
    } catch (error) { this.db.exec('ROLLBACK'); throw error; }
    return this.read();
  }
  favorites() {
    const { revision, settings } = this.read();
    const ids = new Set(this.db.prepare('SELECT project_id FROM project_favorites WHERE favorite=1').all().map(row => String(row.project_id)));
    return { revision, ids: settings.projects.filter(project => ids.has(project.id)).map(project => project.id) };
  }
  setFavorite(expectedRevision, id, favorite) {
    if (typeof favorite !== 'boolean') invalid('Expected a boolean favorite');
    this.db.exec('BEGIN IMMEDIATE');
    try {
      const before = this.read();
      this.assertRevision(expectedRevision, before.revision);
      if (!before.settings.projects.some(entry => entry.id === id)) invalid('Choose a saved project');
      this.db.prepare('INSERT INTO project_favorites VALUES(?,?) ON CONFLICT(project_id) DO UPDATE SET favorite=excluded.favorite').run(id, Number(favorite));
      this.db.prepare('UPDATE local_settings SET revision=revision+1 WHERE id=1').run();
      this.db.exec('COMMIT');
    } catch (error) { this.db.exec('ROLLBACK'); throw error; }
    return this.favorites();
  }
  async importLegacy(expected, { orchestration, models }, options) {
    const before = this.read(); this.assertRevision(expected, before.revision);
    if (before.revision !== 0 || before.imported) invalid('Import is only available before settings have been configured');
    const next = defaultSettings();
    if (orchestration) {
      next.projects = orchestration.repositories.map(repo => ({ id: repo.id, name: repo.id, path: repo.path, enabled: true, github: repo.github, remote: repo.remote.url,
        checks: repo.checks.map(check => ({ id: check.id, executable: check.bin, args: check.argv.slice(1) })) }));
      next.provider = orchestration.native.engine.provider;
      const provider = next.providers[next.provider];
      if (!provider) invalid('Legacy provider is unsupported');
      provider.executable = orchestration.native.ccsBin; provider.model = orchestration.native.engine.model;
      next.tools.cmux = orchestration.native.cmux.bin;
      Object.assign(next.execution, orchestration.policy, orchestration.limits);
    }
    if (models) {
      if (models.version !== 1) invalid('Unknown legacy model settings version');
      for (const provider of ['claude', 'codex']) next.providers[provider].model = models.roles?.coder?.models?.[provider] ?? next.providers[provider].model;
    }
    validateSettings(next);
    for (const project of next.projects) project.path = (await (options?.inspect ?? inspectProject)(project.path)).path;
    validateSettings(next);
    return this.write(expected, next, true);
  }
  snapshotGoal(goalId, repositoryId, providerResolution, teamSnapshot) {
    const saved = this.goalConfiguration(goalId);
    if (saved) return saved;
    const { revision, settings } = this.read();
    const project = settings.projects.find(entry => entry.id === repositoryId && entry.enabled);
    if (!project) invalid('Choose an enabled project');
    const primary = teamSnapshot?.planner;
    const value = { ...(teamSnapshot ? { profiles: teamSnapshot.profiles, teamConfiguration: teamSnapshot.configuration } : {}), project, provider: primary?.provider ?? settings.provider, command: primary?.command ?? settings.providers[settings.provider], ...((primary?.providerResolution ?? providerResolution) ? { providerResolution: primary?.providerResolution ?? providerResolution } : {}), tools: settings.tools, execution: settings.execution };
    this.db.prepare('INSERT INTO goal_configuration VALUES(?,?,?)').run(goalId, revision, JSON.stringify(value));
    return { revision, ...value };
  }
  goalConfiguration(goalId) {
    const row = this.db.prepare('SELECT revision,value FROM goal_configuration WHERE goal_id=?').get(goalId);
    return row ? { revision: Number(row.revision), ...JSON.parse(String(row.value)) } : null;
  }
  close() { this.db.close(); }
}
